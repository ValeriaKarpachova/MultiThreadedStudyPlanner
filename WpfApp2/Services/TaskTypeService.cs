namespace WpfApp2.Services
{
    public static class TaskTypeService
    {
        public static int GetImportance(string type)
        {
            return type switch
            {
                "Іспит" or "Дипломний проєкт" => 10,
                "Тест" or "Практика" => 9,
                "Курсовий проєкт" or "Наукова робота" => 8,
                "Лабораторна робота" => 7,
                "Презентація" or "Есе" => 6,
                "Самостійна робота" or "Домашнє завдання" => 5,
                "Практичне заняття" or "Семінар" => 4,
                "Лекція" or "Контрольна робота" => 2,
                _ => 3
            };
        }

        public static double GetDefaultHours(string type)
        {
            return type switch
            {
                "Дипломний проєкт" => 80,
                "Курсовий проєкт" => 25,
                "Наукова робота" => 20,
                "Практика" => 120,
                "Іспит" => 12,
                "Тест" => 6,
                "Контрольна робота" => 5,
                "Лабораторна робота" => 4,
                "Практичне заняття" => 3,
                "Семінар" => 2,
                "Домашнє завдання" => 2,
                "Есе" => 5,
                "Презентація" => 6,
                "Самостійна робота" => 3,
                "Лекція" => 1,
                _ => 3
            };
        }

        public static List<string> GetDefaultSubTaskNames(string? type, int parts)
        {
            var templates = type switch
            {
                "Дипломний проєкт" => new[] {
                    "Вступ",
                    "Розділ 1",
                    "Розділ 2",
                    "Розділ 3",
                    "Розділ 4",
                    "Висновки",
                    "Список літератури"
                },

                "Курсовий проєкт" => new[] {
                    "Вступ",
                    "Теоретична частина",
                    "Практична частина",
                    "Висновки"
                },

                "Наукова робота" => new[] {
                    "Вступ",
                    "Огляд літератури",
                    "Методологія",
                    "Результати",
                    "Висновки"
                },

                "Іспит" => new[] {
                    "Повторення теорії",
                    "Практичні задачі",
                    "Пробний іспит",
                    "Фінальне повторення"
                },

                "Тест" => new[] {
                    "Повторення матеріалу",
                    "Практика",
                    "Самоперевірка"
                },

                "Практика" => new[] {
                    "Ознайомлення",
                    "Основна робота",
                    "Звіт",
                    "Захист"
                },

                "Лабораторна робота" => new[] {
                    "Підготовка",
                    "Виконання",
                    "Оформлення звіту"
                },

                "Есе" or "Презентація" => new[] {
                    "Збір матеріалу",
                    "План і структура",
                    "Створення",
                    "Редагування"
                },

                _ => Enumerable.Range(1, parts)
                               .Select(i => $"Частина {i}")
                               .ToArray()
            };

            var result = templates.Take(parts).ToList();

            while (result.Count < parts)
                result.Add($"Частина {result.Count + 1}");

            return result;
        }
    }
}